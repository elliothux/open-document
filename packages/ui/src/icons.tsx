const allArtwork = { ...artwork, ...panelArtwork };

export type IconName = keyof typeof allArtwork;

export function Icon({ name }: { name: IconName }) {
  return (
    <svg
      width="18"
      height="18"
      viewBox="0 0 16 16"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.333"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {allArtwork[name]}
    </svg>
  );
}
